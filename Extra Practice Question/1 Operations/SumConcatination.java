public class SumConcatination
{
	public static void main(String args[])
	{
		int a = 5; //store 4 bytes in memory
		int b = 4; // store 4 bytes in memort
		int sum = a + b;
		System.out.println("Sum of " + a + " and " + b + " is " + sum); // with the help of + operater we are doing the concatinations in string and integer
	}
	
	
	
					/*

					Rules of concatination:

					integer + integer = integer  e.g  2 + 3 = 5
					integer + string = string	e.g   5 + "Hello" = "5Hello"
					string + integer = string   e.g   "Hello" + 10 = "Hello10"
					string + string = string   e.g    "Hello" + "World" = "HelloWorld"

					*/
					
					

					
					
}
